export function getSizePricing(product: Pick<Product, "sizes" | "priceMin" | "priceMax">) {
  const steps = Math.max(product.sizes.length - 1, 1);
  return product.sizes.map((size, i) => ({
    size,
    price:
      Math.round((product.priceMin + ((product.priceMax - product.priceMin) * i) / steps) / 10) *
      10,
  }));
}

export function formatPrice(value: number) {
  return `${value.toLocaleString("ro-RO")} lei`;
}

